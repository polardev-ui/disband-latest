// Keyframe handoff for the Anonymous Accounts spot, sampled from the stage
// itself so it always matches the render.
//   node anon/handoff.mjs  -> anon/handoff.json, anon/HANDOFF.md
//
// For every cue time it records each named layer (data-layer on DOM elements,
// named groups in the 3D scene): screen position (px, 1080×1920, origin top
// left), for 3D layers also world position (scene units), scale, rotation
// (degrees) and opacity.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright";
import { serve } from "../tools/serve.mjs";

const tl = await import(pathToFileURL(path.resolve("anon/timeline.js")).href);
const { T, FPS, DURATION, SHOTS, COPY } = tl;

const flat = Object.values(T).flatMap((v) => (Array.isArray(v) ? v : [v]));
const times = [...new Set([0, ...flat, ...SHOTS.map(([s]) => s), DURATION - 1 / FPS]
  .map((t) => Math.round(Math.min(t, DURATION - 1 / FPS) * FPS) / FPS))].sort((a, b) => a - b);

const { server, origin } = await serve();
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1080, height: 1920 } });
page.on("pageerror", (e) => console.error("pageerror", e.message));
await page.goto(`${origin}/anon/stage.html?preview`);
await page.waitForSelector("body[data-ready]", { timeout: 300000 });

const r2 = (v) => Math.round(v * 100) / 100;
const samples = [];
for (const t of times) {
  await page.evaluate((tt) => window.renderFrame(tt), t);
  const rows = await page.evaluate(() => {
    const out = [];
    const visible = (el) => { for (let e = el; e && e !== document.body; e = e.parentElement) { const cs = getComputedStyle(e); if (cs.display === "none" || cs.visibility === "hidden") return false; } return true; };
    for (const el of document.querySelectorAll("[data-layer]")) {
      if (!visible(el)) continue;
      const r = el.getBoundingClientRect();
      let op = 1;
      for (let e = el; e && e !== document.body; e = e.parentElement) op *= Number(getComputedStyle(e).opacity);
      const m = new DOMMatrix(getComputedStyle(el).transform === "none" ? undefined : getComputedStyle(el).transform);
      out.push({
        layer: el.dataset.layer, source: `dom:${el.id || el.dataset.key || el.className}`,
        screenX: r.left + r.width / 2, screenY: r.top + r.height / 2, width: r.width, height: r.height,
        scale: Math.hypot(m.a, m.b), rotZ: (Math.atan2(m.b, m.a) * 180) / Math.PI, opacity: op,
        text: (el.innerText || "").replace(/\s+/g, " ").trim().slice(0, 80),
      });
    }
    const shots = window.__shots, cam = window.__engine.camera;
    for (const [name, g] of Object.entries(shots.layers)) {
      let vis = true;
      for (let o = g; o; o = o.parent) if (!o.visible) vis = false;
      if (!vis) continue;
      const P = g.position.constructor, Q = g.quaternion.constructor;
      const p = g.getWorldPosition(new P()), q = g.getWorldQuaternion(new Q()), s = g.getWorldScale(new P());
      const e = new g.rotation.constructor().setFromQuaternion(q);
      const sp = p.clone().project(cam);
      out.push({
        layer: name, source: "3d",
        worldX: p.x, worldY: p.y, worldZ: p.z,
        screenX: (sp.x + 1) * 540, screenY: (1 - sp.y) * 960,
        scale: s.x, rotX: (e.x * 180) / Math.PI, rotY: (e.y * 180) / Math.PI, rotZ: (e.z * 180) / Math.PI, opacity: 1,
      });
    }
    return out;
  });
  for (const row of rows) {
    for (const k of Object.keys(row)) if (typeof row[k] === "number") row[k] = r2(row[k]);
    samples.push({ t, frame: Math.round(t * FPS), ...row });
  }
  process.stdout.write(".");
}
await browser.close();
server.close();

const layers = {};
for (const s of samples) (layers[s.layer] ??= []).push(s);
const doc = {
  title: "Disband — Anonymous Accounts (9:16) keyframes",
  fps: FPS, duration: DURATION, frame: { width: 1080, height: 1920 },
  units: { screen: "px, origin top-left", world: "scene units (camera fov 30°, vertical)", rotation: "degrees" },
  copy: COPY, cues: T, shots: SHOTS, layers,
};
fs.writeFileSync("anon/handoff.json", JSON.stringify(doc, null, 2));

const md = [
  "# Disband — Anonymous Accounts (9:16): keyframe handoff",
  "",
  `${FPS} fps · ${DURATION.toFixed(1)} s · 1080×1920. Generated by \`node anon/handoff.mjs\` from the stage itself; \`handoff.json\` has every value.`,
  "Screen positions are layer centres in px (origin top-left). 3D layers also give world position in scene units.",
  "",
  "## Shots",
  "",
  "| Start | Shot |",
  "|---:|---|",
  ...SHOTS.map(([s, n]) => `| ${s.toFixed(2)} s | ${n} |`),
  "",
];
for (const [name, rows] of Object.entries(layers)) {
  md.push(`## ${name}`, "", "| t (s) | frame | source | screen x | screen y | world x/y/z | scale | rot x/y/z | opacity | text |", "|---:|---:|---|---:|---:|---|---:|---|---:|---|");
  for (const r of rows) {
    const w = r.source === "3d" ? `${r.worldX} / ${r.worldY} / ${r.worldZ}` : "";
    const rot = r.source === "3d" ? `${r.rotX} / ${r.rotY} / ${r.rotZ}` : `0 / 0 / ${r.rotZ}`;
    md.push(`| ${r.t.toFixed(2)} | ${r.frame} | ${r.source} | ${r.screenX} | ${r.screenY} | ${w} | ${r.scale} | ${rot} | ${r.opacity} | ${(r.text || "").replace(/\|/g, "/")} |`);
  }
  md.push("");
}
fs.writeFileSync("anon/HANDOFF.md", md.join("\n"));
console.log(`\nwrote anon/handoff.json and anon/HANDOFF.md: ${times.length} keyframe times, ${samples.length} samples, layers: ${Object.keys(layers).join(", ")}`);
