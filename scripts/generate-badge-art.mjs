#!/usr/bin/env node
/*
 Badge artwork for every platform, from one source.

 src/components/ui/BadgeArt.tsx holds the emblems the web and desktop draw.
 This script reads that file and writes the same shapes for the native apps:

   ios/DisbandiOS/Resources/Assets.xcassets/Badges/badge_<key>.imageset  (SVG, kept as vectors)
   android/app/src/main/res/drawable/badge_<key>.xml                     (VectorDrawable)

 Edit BadgeArt.tsx, run `node scripts/generate-badge-art.mjs`, and commit the
 output. Nothing here is drawn by hand twice.
*/
import { mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "src/components/ui/BadgeArt.tsx"), "utf8");

// --- Parse the ART table -----------------------------------------------------

const art = {};
const entry = /^\s+(\w+): <>(.*)<\/>,\s*$/gm;
for (const [, key, body] of source.matchAll(entry)) {
  const shapes = [];
  for (const [, tag, attrs] of body.matchAll(/<(path|circle|rect)\s+([^>]*?)\s*\/>/g)) {
    const props = {};
    for (const [, name, quoted, braced] of attrs.matchAll(/(\w+)=(?:"([^"]*)"|\{([^}]*)\})/g)) {
      props[name] = quoted ?? braced.replace(/^"|"$/g, "");
    }
    shapes.push({ tag, props });
  }
  if (shapes.length === 0) throw new Error(`No shapes parsed for badge "${key}"`);
  art[key] = shapes;
}
const keys = Object.keys(art);
if (keys.length < 20) throw new Error(`Only ${keys.length} badges parsed; BadgeArt.tsx format changed?`);

// --- Shapes as path data (VectorDrawable has no circle or rect) --------------

function circlePath({ cx, cy, r }) {
  const [x, y, rr] = [cx, cy, r].map(Number);
  return `M${x - rr},${y}a${rr},${rr} 0 1,0 ${rr * 2},0a${rr},${rr} 0 1,0 ${-rr * 2},0Z`;
}

function rectPath({ x = 0, y = 0, width, height, rx = 0 }) {
  const [X, Y, W, H] = [x, y, width, height].map(Number);
  const R = Math.min(Number(rx), W / 2, H / 2);
  if (!R) return `M${X},${Y}h${W}v${H}h${-W}Z`;
  return `M${X + R},${Y}h${W - 2 * R}a${R},${R} 0 0,1 ${R},${R}v${H - 2 * R}a${R},${R} 0 0,1 ${-R},${R}h${-(W - 2 * R)}a${R},${R} 0 0,1 ${-R},${-R}v${-(H - 2 * R)}a${R},${R} 0 0,1 ${R},${-R}Z`;
}

const pathData = ({ tag, props }) =>
  tag === "path" ? props.d : tag === "circle" ? circlePath(props) : rectPath(props);

// --- SVG for iOS -------------------------------------------------------------

const svgAttr = { strokeWidth: "stroke-width", strokeLinecap: "stroke-linecap", strokeLinejoin: "stroke-linejoin", fillRule: "fill-rule" };

function svg(shapes) {
  const body = shapes
    .map(({ tag, props }) => {
      const attrs = Object.entries(props)
        .map(([k, v]) => `${svgAttr[k] ?? k}="${v}"`)
        .join(" ");
      return `  <${tag} ${attrs}/>`;
    })
    .join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">\n${body}\n</svg>\n`;
}

// --- VectorDrawable for Android ----------------------------------------------

function vector(shapes) {
  const paths = shapes
    .map((shape) => {
      const { props } = shape;
      const a = [`android:pathData="${pathData(shape)}"`];
      if (props.fill && props.fill !== "none") a.push(`android:fillColor="${props.fill}"`);
      if (props.stroke) a.push(`android:strokeColor="${props.stroke}"`);
      if (props.strokeWidth) a.push(`android:strokeWidth="${props.strokeWidth}"`);
      if (props.strokeLinecap) a.push(`android:strokeLineCap="${props.strokeLinecap}"`);
      if (props.strokeLinejoin) a.push(`android:strokeLineJoin="${props.strokeLinejoin}"`);
      if (props.fillRule === "evenodd") a.push(`android:fillType="evenOdd"`);
      return `    <path\n        ${a.join("\n        ")} />`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-badge-art.mjs from src/components/ui/BadgeArt.tsx. Do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n${paths}\n</vector>\n`;
}

// --- Write -------------------------------------------------------------------

const iosDir = join(root, "ios/DisbandiOS/Resources/Assets.xcassets/Badges");
rmSync(iosDir, { recursive: true, force: true });
mkdirSync(iosDir, { recursive: true });
writeFileSync(join(iosDir, "Contents.json"), JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n");

const androidDir = join(root, "android/app/src/main/res/drawable");
mkdirSync(androidDir, { recursive: true });
for (const file of readdirSync(androidDir)) {
  if (/^badge_\w+\.xml$/.test(file)) rmSync(join(androidDir, file));
}

for (const key of keys) {
  const set = join(iosDir, `badge_${key}.imageset`);
  mkdirSync(set);
  writeFileSync(join(set, `badge_${key}.svg`), svg(art[key]));
  writeFileSync(
    join(set, "Contents.json"),
    JSON.stringify(
      {
        images: [{ filename: `badge_${key}.svg`, idiom: "universal" }],
        info: { author: "xcode", version: 1 },
        properties: { "preserves-vector-representation": true, "template-rendering-intent": "original" },
      },
      null,
      2,
    ) + "\n",
  );
  writeFileSync(join(androidDir, `badge_${key}.xml`), vector(art[key]));
}

console.log(`Generated ${keys.length} badges: ${keys.join(", ")}`);
